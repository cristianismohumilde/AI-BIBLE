def make_sefaria_json(book_name, column_num, lines, source="DSS Acadêmico (Abegg)"):
    """Cria um JSON no formato Sefaria para salvar em data/DSS/{book}/{col}.json"""
    return {
        "ref": f"{book_name} {column_num}",
        "heRef": f"{book_name} עמוד {column_num}",
        "isComplex": False,
        "text": [],
        "he": lines,
        "textDepth": 1,
        "sectionNames": ["Coluna"],
        "addressTypes": ["Integer"],
        "lengths": [len(lines)],
        "length": len(lines),
        "heTitle": book_name,
        "titleVariants": [book_name],
        "heTitleVariants": [book_name],
        "type": "DSS",
        "primary_category": "Dead Sea Scrolls",
        "book": book_name,
        "categories": ["Dead Sea Scrolls", "Textos Sectários"],
        "sections": [column_num],
        "versionTitle": "Transcrição Acadêmica (Martin Abegg Jr. / ETCBC)",
        "versionSource": source,
        "versionStatus": "locked",
        "versionNotes": "Texto hebraico qumrânico sem pontuação massorética — baseado na transcrição de Martin Abegg Jr.",
        "license": "Public Domain",
    }


def save_scroll(scroll_id, columns_data):
    """Salva um rolo sectário em data/DSS/{scroll_id}/"""
    out_dir = os.path.join(DATA_DIR, scroll_id)
    os.makedirs(out_dir, exist_ok=True)
    saved = 0
    for col_num, lines in columns_data.items():
        out_file = os.path.join(out_dir, f"{col_num}.json")
        if os.path.exists(out_file):
            print(f"  ⏭️  {scroll_id} Coluna {col_num} já existe, pulando...")
            continue
        data = make_sefaria_json(scroll_id, col_num, lines)
        with open(out_file, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
        saved += 1
        print(f"  ✅ {scroll_id}/{col_num}.json salvo ({len(lines)} linhas)")
    return saved


def verify_isaiah():
    """Verifica se 1QIsa-a está presente via data/DSS/Isaiah."""
    isa_dir = os.path.join(DATA_DIR, "Isaiah")
    if os.path.isdir(isa_dir):
        count = len([f for f in os.listdir(isa_dir) if f.endswith(".json")])
        print(f"  ✅ Isaiah (1QIsa-a): {count} capítulos disponíveis em data/DSS/Isaiah/")
        return True
    else:
        print(f"  ❌ Isaiah não encontrado em data/DSS/Isaiah/")
        return False


